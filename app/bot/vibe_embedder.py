"""Runtime vibe resolver backed by a pre-computed embedding cache.

Loads ``app/bot/vibe_embeddings.json`` (generated by
``scripts/build_vibe_embeddings.py``) at import time. Serves as the
second-line resolver in ``suggest_gifts``:

  1. Gemini's enum pick (primary) — issue #009 Gap G9.
  2. This module's ``resolve(text)`` (embedder) — Gap G10.
  3. Keyword-map ``_resolve_one`` (legacy fallback) — Gap G8.

The embedder exists for the cases where (1) is bypassed — e.g. a tool
call that slipped through with free-form ``recipient_vibe`` text, or a
multilingual input the keyword map doesn't cover. It is async because
the embedding API call is I/O-bound.

No new runtime dependencies — stdlib (``json``, ``math``) + the
``google.genai`` SDK already used elsewhere in the project.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import math
import os
from pathlib import Path
from typing import Any

logger = logging.getLogger("wishkr.vibe_embedder")


async def _async_log_embedding_usage(
    model: str,
    latency_ms: float,
    input_tokens: int = 100,  # rough estimate per query
) -> None:
    """Log embedding call usage. Fire-and-forget task.

    This function is spawned as an asyncio.create_task() so it doesn't block
    the caller. Any exceptions are logged but don't interrupt the main flow.
    This is best-effort logging: if the database is unavailable, the request
    still succeeds (the embedding is returned) but the usage isn't recorded.
    """
    try:
        from sqlalchemy.ext.asyncio import AsyncSession
        from sqlalchemy.orm import sessionmaker as async_sessionmaker
        from app.models.llm_usage_event import LlmUsageEvent
        from app.utils.llm_cost import estimate_cost
        from app.utils.id_gen import generate_id
        from app.db.session import create_resilient_async_engine

        # Get DB URL from env/config
        db_url = os.environ.get("DATABASE_URL") or "postgresql+asyncpg://wishkr:wishkr_dev@localhost:5432/wishkr"
        engine = create_resilient_async_engine(db_url)
        async_session = async_sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)

        try:
            async with async_session() as session:
                estimated_cost = estimate_cost(
                    model=model,
                    input_tokens=input_tokens,
                    output_tokens=0,  # Embeddings have no discrete output tokens
                )

                event = LlmUsageEvent(
                    id=generate_id("llu"),
                    provider="google_genai",
                    model=model,
                    purpose="embedding",
                    phase=None,
                    conversation_id=None,
                    phone_hash=None,
                    input_tokens=input_tokens,
                    output_tokens=0,
                    cache_hit_tokens=None,
                    total_tokens=input_tokens,
                    estimated_cost_usd=estimated_cost,
                    latency_ms=int(latency_ms),
                    success=True,
                    error_type=None,
                    fallback_used=False,
                    tool_calls_count=None,
                )
                session.add(event)
                await session.commit()
        finally:
            await engine.dispose()
    except Exception as e:
        logger.exception("failed to log embedding usage: %s", e)

_CACHE_PATH = Path(__file__).resolve().parent / "vibe_embeddings.json"

# Similarity threshold — empirical; below this the match is typically
# coincidental word overlap. Tightened from 0.55 → 0.62 after the
# "extrovert who hates meeting people" incident where the resolver
# returned candles + perfume + cleaning_services for a contradictory
# persona at sub-0.6 scores.
DEFAULT_THRESHOLD = 0.62
DEFAULT_TOP_K = 3
# Long phrases (5+ words) signal complex / contradictory personas where
# embedding similarity is unreliable. Require a stronger top match.
LONG_QUERY_WORD_COUNT = 5
LONG_QUERY_THRESHOLD = 0.68


# ─────────────────────────────────────────────────────────
# Cache loading (once, at import)
# ─────────────────────────────────────────────────────────

_cache: dict[str, Any] | None = None
_cache_load_err: str | None = None


def _load_cache() -> dict[str, Any] | None:
    """Load the pre-computed embeddings. Returns None on any failure
    (missing file, invalid JSON, schema mismatch). Callers must tolerate
    a None cache — the resolver will no-op and suggest_gifts falls through
    to the keyword fallback. Never raise."""
    global _cache_load_err

    if not _CACHE_PATH.exists():
        _cache_load_err = f"cache file not found: {_CACHE_PATH.name}"
        logger.warning(
            "vibe_embedder: no cache file — resolver will no-op. "
            "Run scripts/build_vibe_embeddings.py to generate."
        )
        return None

    try:
        with _CACHE_PATH.open() as f:
            data = json.load(f)
    except Exception as e:  # broad on purpose — any read error
        _cache_load_err = f"load failed: {e}"
        logger.warning("vibe_embedder: cache unreadable (%s) — no-op", e)
        return None

    expected_keys = {"model", "output_dim", "taxonomy_hash", "embeddings"}
    if not expected_keys.issubset(data):
        _cache_load_err = "schema missing keys"
        logger.warning("vibe_embedder: cache schema invalid — no-op")
        return None

    # Compare taxonomy hash with the current runtime taxonomy so a
    # stale cache surfaces as a warning (not a crash).
    try:
        from app.bot.gift_taxonomy import (
            all_vibe_ids,
            VIBE_TO_HUBBLE_BRANDS,
            VIBE_TO_VENDOR_CATEGORIES,
        )
        payload = {
            "vibes": sorted(all_vibe_ids()),
            "brands": {k: sorted(v) for k, v in VIBE_TO_HUBBLE_BRANDS.items()},
            "vendors": {k: sorted(v) for k, v in VIBE_TO_VENDOR_CATEGORIES.items()},
        }
        live_hash = hashlib.sha256(
            json.dumps(payload, sort_keys=True).encode()
        ).hexdigest()[:16]
        if live_hash != data.get("taxonomy_hash"):
            logger.warning(
                "vibe_embedder: taxonomy_hash drift (cache=%s live=%s) — "
                "cache may miss recent vibes. Run scripts/build_vibe_embeddings.py.",
                data.get("taxonomy_hash"), live_hash,
            )
    except Exception:
        logger.exception("vibe_embedder: taxonomy hash check failed (non-fatal)")

    logger.info(
        "vibe_embedder: loaded %d vectors (model=%s, dim=%d)",
        len(data.get("embeddings", {})),
        data.get("model"),
        data.get("output_dim"),
    )
    return data


_cache = _load_cache()


def is_ready() -> bool:
    """True when the cache loaded cleanly and the resolver can serve queries."""
    return _cache is not None and bool(_cache.get("embeddings"))


def cache_status() -> dict[str, Any]:
    """Diagnostic snapshot for /health style endpoints."""
    if _cache is None:
        return {"ready": False, "error": _cache_load_err or "unknown"}
    return {
        "ready": True,
        "model": _cache.get("model"),
        "output_dim": _cache.get("output_dim"),
        "vibe_count": _cache.get("vibe_count"),
        "taxonomy_hash": _cache.get("taxonomy_hash"),
    }


# ─────────────────────────────────────────────────────────
# Runtime resolution
# ─────────────────────────────────────────────────────────

def _normalise(vec: list[float]) -> list[float]:
    n = math.sqrt(sum(x * x for x in vec))
    if n == 0:
        return vec
    return [x / n for x in vec]


def _cosine_prenorm(q_unit: list[float], v_unit: list[float]) -> float:
    """Cosine similarity for already-normalised vectors."""
    return sum(a * b for a, b in zip(q_unit, v_unit))


# Embedding-API client — imported lazily so tests / non-embedding paths
# don't pay for an SDK import they don't need.
_genai_client = None
_genai_types_mod = None


def _get_client():
    global _genai_client, _genai_types_mod
    if _genai_client is None:
        api_key = os.environ.get("GEMINI_API_KEY")
        if not api_key:
            raise RuntimeError("GEMINI_API_KEY is not set")
        from google import genai
        from google.genai import types as genai_types
        _genai_client = genai.Client(api_key=api_key)
        _genai_types_mod = genai_types
    return _genai_client, _genai_types_mod


async def _embed_query(text: str) -> list[float] | None:
    """Embed a query string with the same model used at build time.

    Runs the blocking SDK call in a thread so the event loop isn't stalled.
    Returns None on any API failure — the resolver then no-ops rather
    than raising, so the caller can fall through to keyword matching.
    """
    if not _cache:
        return None
    model = _cache.get("model", "text-embedding-004")
    output_dim = _cache.get("output_dim", 768)

    try:
        client, types_mod = _get_client()
    except Exception as e:
        logger.warning("vibe_embedder: genai client unavailable: %s", e)
        return None

    import time
    start_time = time.time()
    try:
        def _call():
            return client.models.embed_content(
                model=model,
                contents=text,
                config=types_mod.EmbedContentConfig(
                    task_type="RETRIEVAL_QUERY",
                    output_dimensionality=output_dim,
                ),
            )
        resp = await asyncio.to_thread(_call)
        values = list(resp.embeddings[0].values)
        return _normalise(values)
    except Exception as e:
        logger.warning("vibe_embedder: embed_content failed: %s", e)
        return None
    finally:
        # Log embedding usage asynchronously
        latency_ms = (time.time() - start_time) * 1000
        task = asyncio.create_task(_async_log_embedding_usage(
            model=model,
            latency_ms=latency_ms,
        ))
        # Add callback to log any unhandled exceptions in the background task
        def _log_task_error(t):
            if t.cancelled():
                return
            exc = t.exception()
            if exc:
                logger.warning("embedding usage logging task failed: %s", exc)
        task.add_done_callback(_log_task_error)


async def resolve(
    text: str,
    *,
    top_k: int = DEFAULT_TOP_K,
    threshold: float = DEFAULT_THRESHOLD,
) -> list[str]:
    """Return canonical vibe IDs semantically closest to ``text``.

    ``text`` is a free-form phrase in any language Gemini understands.
    Results are sorted by similarity, filtered by ``threshold``, and
    truncated to ``top_k``. Returns ``[]`` if the cache is unavailable,
    the embedding API is down, or nothing clears the threshold — the
    caller should then fall back to its next resolver (keyword map).

    This is additive: `resolve(text)` never raises and never returns
    invalid vibe IDs — everything it emits is already in the canonical
    taxonomy.
    """
    if not text or not _cache:
        return []

    q = await _embed_query(text.strip())
    if q is None:
        return []

    # Long phrases are usually contradictory personas ("extrovert who
    # hates meeting people"). Require a stronger top hit before we
    # commit to suggestions instead of returning low-confidence noise.
    word_count = len(text.split())
    effective_threshold = (
        LONG_QUERY_THRESHOLD
        if word_count >= LONG_QUERY_WORD_COUNT
        else threshold
    )

    embeds = _cache["embeddings"]
    scored: list[tuple[str, float]] = []
    for vibe_id, v_unit in embeds.items():
        sim = _cosine_prenorm(q, v_unit)
        if sim >= effective_threshold:
            scored.append((vibe_id, sim))

    scored.sort(key=lambda pair: pair[1], reverse=True)
    if not scored:
        logger.info(
            "vibe_embedder: no match >= %.2f for %r (words=%d)",
            effective_threshold, text[:80], word_count,
        )
    return [vid for vid, _ in scored[:top_k]]
